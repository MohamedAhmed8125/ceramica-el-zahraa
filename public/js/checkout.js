  /* ---------- التحقق ---------- */
  function validate() {
    const d = S.d, e = {};
    if (!EMAIL_RE.test(d.email.trim())) e.email = 'co_e_email';
    if (!normalizePhone(d.phone)) e.phone = 'co_e_phone';
    if (d.first.trim().length < 2) e.first = 'co_e_first';
    if (d.last.trim().length < 2) e.last = 'co_e_last';
    if (d.shipping === 'delivery') {
      if (!S.cfg.governorates.some(g => g.id === d.gov)) e.gov = 'co_e_gov';
      if (d.city.trim().length < 2) e.city = 'co_e_city';
      if (d.address.trim().length < 5) e.address = 'co_e_address';
    }
    S.errors = e;
    return !Object.keys(e).length;
  }

  async function placeOrder() {
    if (!S.pay) { S.errors = { pay: 'co_e_pay' }; return render(); }
    const d = S.d;
    S.placing = true; S.serverError = ''; render();
    try {
      const r = await fetch('/api/orders', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          items: S.lines.map(l => ({ id: l.id, qty: l.qty })),
          shipping: d.shipping, payment: S.pay, lang,
          customer: {
            firstName: d.first, lastName: d.last, email: d.email, phone: normalizePhone(d.phone),
            governorate: d.gov, city: d.city, address: d.address, notes: d.notes
          }
        })
      });
      const data = await r.json().catch(() => ({}));
      if (r.ok) { S.done = data.order; Cart.clear(); }
      else S.serverError = data.error || 'network';
    } catch { S.serverError = 'network'; }
    S.placing = false;
    window.scrollTo(0, 0);
    render();
  }

  /* ---------- الأحداث ---------- */
  root.addEventListener('input', e => {
    const k = e.target.dataset.k;
    if (k) S.d[k] = e.target.value;
  });

  root.addEventListener('change', e => {
    const el = e.target;
    if (el.name === 'ship') { S.d.shipping = el.value; S.errors = {}; render(); }
    else if (el.name === 'pay') { S.pay = el.value; S.errors = {}; S.serverError = ''; render(); }
  });

  root.addEventListener('click', e => {
    const b = e.target.closest('[data-go]');
    if (!b) return;
    switch (b.dataset.go) {
      case 'next':
        if (validate()) { S.step = 2; window.scrollTo(0, 0); render(); }
        else {
          render();
          const bad = root.querySelector('.is-err input, .is-err select');
          if (bad) bad.focus();
        }
        break;
      case 'edit': S.step = 1; S.serverError = ''; window.scrollTo(0, 0); render(); break;
      case 'place': placeOrder(); break;
    }
  });

  document.addEventListener('langchange', render);

  /* ---------- البداية ---------- */
  (async function init() {
    try { S.cfg = await (await fetch('/api/checkout-config')).json(); }
    catch { S.cfg = { governorates: [], shippingFee: null, pickup: true, instapayNumber: '' }; }
    if (!S.cfg.pickup) S.d.shipping = 'delivery';

    const cart = Cart.get();
    const prods = await Promise.all(cart.map(i => Catalog.byId(i.id)));
    S.lines = cart.map((i, k) => ({ id: i.id, qty: i.qty, p: prods[k] }));
    S.issue = S.lines.some(l => !l.p || l.p.stock <= 0 || l.qty > l.p.stock);

    // لو العميل مسجل دخول، بنملّي اسمه وإيميله
    try {
      const r = await fetch('/api/me');
      if (r.ok) {
        const { user } = await r.json();
        const parts = String(user.name || '').split(' ');
        S.d.email = user.email || '';
        S.d.first = parts[0] || '';
        S.d.last = parts.slice(1).join(' ');
      }
    } catch {}
    render();
  })();
